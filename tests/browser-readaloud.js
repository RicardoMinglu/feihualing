async page => {
  const base='http://127.0.0.1:8765', checks=[];
  const check=(name,ok)=>{if(!ok)throw Error(name);checks.push(name)};
  await page.goto(base);
  await page.evaluate(()=>localStorage.removeItem('feihualing.game'));
  await page.reload();
  await page.evaluate(()=>{
    window.__spoken=[];window.__cancelled=0;
    window.SpeechSynthesisUtterance=class {constructor(text){this.text=text}};
    Object.defineProperty(window,'speechSynthesis',{configurable:true,value:{getVoices:()=>[{lang:'zh-CN',name:'Chinese'}],speak(u){window.__spoken.push(u)},cancel(){window.__cancelled++},addEventListener(){},removeEventListener(){}}});
  });
  await page.getByRole('link',{name:'查诗'}).click();
  await page.locator('.result-item').first().waitFor();
  check('no microphone control',await page.locator('#voice').count()===0);
  await page.locator('.result-item .read-btn').first().click();
  check('search read',await page.evaluate(()=>__spoken.length===1&&__spoken[0].rate===.9&&__spoken[0].voice.lang==='zh-CN'));
  await page.locator('.result-item .read-btn').nth(1).click();
  check('switch cancels old reading',await page.evaluate(()=>__spoken.length===2&&__cancelled>=2));
  await page.locator('.result-item .read-btn').nth(1).click();
  check('same button stops',await page.locator('.result-item .read-btn').nth(1).getAttribute('aria-pressed')==='false');
  await page.locator('.result-open').first().click();await page.getByRole('dialog').waitFor();
  await page.locator('.modal-commands .read-btn').click();
  check('full poem title starts narration',await page.evaluate(()=>__spoken.at(-1).text.includes('，')));
  await page.evaluate(()=>__spoken.at(-1).onend());
  check('full poem reads author next',await page.evaluate(()=>__spoken.at(-1).text.includes('。')));
  await page.getByRole('button',{name:'关闭'}).click();
  check('modal close stops',await page.evaluate(()=>!speechSynthesis.speaking||__cancelled>=4));
  await page.getByRole('link',{name:'人机对战'}).click();
  await page.getByRole('button',{name:'开始对战',exact:true}).click();
  await page.waitForURL('**#battle');
  let answers=0;page.on('request',r=>{if(r.url().endsWith('/answers'))answers++});
  const input=page.getByRole('textbox',{name:'输入诗句'});
  await input.fill('床前明月光');check('typing does not judge',answers===0);
  await input.dispatchEvent('compositionstart');
  await input.press('Enter');check('IME Enter does not submit',answers===0);
  await input.dispatchEvent('compositionend');
  const reply=page.waitForResponse(r=>r.url().endsWith('/answers'));
  await page.getByRole('button',{name:'提交诗句'}).click();
  check('send judges once',(await(await reply).json()).game.round===1&&answers===1);
  await page.locator('.poem-message').first().waitFor();
  await page.waitForFunction(()=>!document.querySelector('.send-btn')?.disabled);
  check('both turns readable',await page.locator('.poem-message .read-btn').count()===2);
  await page.locator('.poem-message .read-btn').first().click();
  check('no answer timer',await page.locator('#countdown').count()===0);
  await page.locator('.poem-message .read-btn').nth(1).click();
  check('battle switch plays canonical line',await page.evaluate(()=>__spoken.at(-1).text.length>0));
  await page.evaluate(()=>{Object.defineProperty(document,'hidden',{configurable:true,value:true});document.dispatchEvent(new Event('visibilitychange'))});
  check('background stops reading',await page.locator('.poem-message .read-btn').nth(1).getAttribute('aria-pressed')==='false');
  await page.evaluate(()=>Object.defineProperty(window,'speechSynthesis',{configurable:true,value:undefined}));
  await page.locator('.poem-message .read-btn').first().click();
  check('unsupported browser shows fallback',(await page.locator('#toast').innerText()).includes('系统浏览器'));
  return {checks};
}
